#include "matcher.h"
#include <pcre2.h>
#include <QByteArrayView>
#include <limits>
#include <stdexcept>

namespace utf8regex {
namespace {
template<class T, auto Free> using Owned = std::unique_ptr<T, decltype(Free)>;
using Code = Owned<pcre2_code, pcre2_code_free>;
using Data = Owned<pcre2_match_data, pcre2_match_data_free>;
using Context = Owned<pcre2_match_context, pcre2_match_context_free>;
using Stack = Owned<pcre2_jit_stack, pcre2_jit_stack_free>;
bool eligible(std::string_view line)
{
    if (line.size() > static_cast<size_t>(std::numeric_limits<qsizetype>::max()))
        throw std::length_error("Line exceeds Qt length range");
    return !(line.size() >= 3 && line.substr(0, 3) == "\xef\xbb\xbf")
        && QByteArrayView(line.data(), static_cast<qsizetype>(line.size())).isValidUtf8();
}
struct Result { bool found = false, bytes = false; qsizetype start = 0, end = 0; };
}
struct Matcher::Impl {
    struct Pattern {
        QRegularExpression qt;
        Code code{nullptr, pcre2_code_free};
        Data data{nullptr, pcre2_match_data_free};
    };
    std::vector<Pattern> patterns;
    Info info;
    Context context{pcre2_match_context_create(nullptr), pcre2_match_context_free};
    Stack stack{nullptr, pcre2_jit_stack_free};
    explicit Impl(const Patterns& input)
    {
        if (!context) throw std::bad_alloc();
        for (const auto& p : input) {
            Pattern item;
            item.qt = static_cast<QRegularExpression>(p);
            if (!item.qt.isValid()) throw std::runtime_error(item.qt.errorString().toStdString());
            if (p.pattern.isValidUtf16()) {
                const auto bytes = item.qt.pattern().toUtf8();
                int error = 0;
                PCRE2_SIZE offset = 0;
                uint32_t options = PCRE2_UTF | PCRE2_UCP | PCRE2_NO_AUTO_CAPTURE | PCRE2_NEVER_BACKSLASH_C;
                if (!p.isCaseSensitive) options |= PCRE2_CASELESS;
                item.code.reset(pcre2_compile(reinterpret_cast<PCRE2_SPTR>(bytes.constData()),
                    static_cast<PCRE2_SIZE>(bytes.size()), options, &error, &offset, nullptr));
            }
            if (item.code) {
                item.data.reset(pcre2_match_data_create_from_pattern(item.code.get(), nullptr));
                if (!item.data) throw std::bad_alloc();
                // JIT is an optional acceleration; inspect actual generated bytes.
                pcre2_jit_compile(item.code.get(), PCRE2_JIT_COMPLETE);
                PCRE2_SIZE bytes = 0, jit = 0;
                if (pcre2_pattern_info(item.code.get(), PCRE2_INFO_SIZE, &bytes) != 0
                    || pcre2_pattern_info(item.code.get(), PCRE2_INFO_JITSIZE, &jit) != 0)
                    throw std::runtime_error("Cannot inspect compiled PCRE program");
                ++info.programs;
                info.codeBytes += bytes;
                info.jitBytes += jit;
                info.jitPrograms += jit != 0;
            } else {
                ++info.fallbackPatterns;
            }
            patterns.push_back(std::move(item));
        }
        if (info.jitPrograms) {
            stack.reset(pcre2_jit_stack_create(32 * 1024, 512 * 1024, nullptr));
            if (!stack) throw std::bad_alloc();
            pcre2_jit_stack_assign(context.get(), nullptr, stack.get());
        }
    }
    Result fallback(size_t index, std::string_view line, std::optional<QString>& decoded, Routing* route) const
    {
        if (route) ++route->fallback;
        if (!decoded) decoded = QString::fromUtf8(line.data(), static_cast<qsizetype>(line.size()));
        const auto result = patterns.at(index).qt.match(*decoded);
        return {result.hasMatch(), false, result.capturedStart(), result.capturedEnd()};
    }
    Result run(size_t index, std::string_view line, bool valid, std::optional<QString>& decoded, Routing* route) const
    {
        const auto& p = patterns.at(index);
        if (!valid || !p.code) return fallback(index, line, decoded, route);
        if (route) ++route->direct;
        const auto* data = reinterpret_cast<PCRE2_SPTR>(line.empty() ? "" : line.data());
        // Whole-line validation above precedes this unchecked UTF-8 match.
        const auto rc = pcre2_match(p.code.get(), data, line.size(), 0, PCRE2_NO_UTF_CHECK,
                                   p.data.get(), context.get());
        if (rc == PCRE2_ERROR_NOMATCH) return {};
        if (rc >= 0) {
            const auto* span = pcre2_get_ovector_pointer(p.data.get());
            if (span[0] <= span[1] && span[1] <= line.size())
                return {true, true, static_cast<qsizetype>(span[0]), static_cast<qsizetype>(span[1])};
        }
        if (route) ++route->runtimeErrors;
        return fallback(index, line, decoded, route);
    }
};
Matcher::Matcher(const Patterns& patterns) : impl_(std::make_unique<Impl>(patterns)) {}
Matcher::~Matcher() = default;
Matcher::Matcher(Matcher&&) noexcept = default;
Matcher& Matcher::operator=(Matcher&&) noexcept = default;
MatchedPatterns Matcher::match(std::string_view line, Routing* route) const
{
    const bool valid = eligible(line);
    std::optional<QString> decoded;
    MatchedPatterns result(impl_->patterns.size(), 0);
    for (size_t i = 0; i < result.size(); ++i) result[i] = impl_->run(i, line, valid, decoded, route).found;
    return result;
}
std::optional<Span> Matcher::firstMatch(size_t pattern, std::string_view line, Routing* route) const
{
    std::optional<QString> decoded;
    const auto result = impl_->run(pattern, line, eligible(line), decoded, route);
    if (!result.found) return {};
    if (!result.bytes) return Span{result.start, result.end - result.start};
    // Decode prefixes, not the isolated match: an interior BOM is a character,
    // whereas QString::fromUtf8 would strip it at the beginning of a substring.
    const auto start = QString::fromUtf8(line.data(), result.start).size();
    const auto end = QString::fromUtf8(line.data(), result.end).size();
    return Span{start, end - start};
}
Info Matcher::info() const { return impl_->info; }
}
